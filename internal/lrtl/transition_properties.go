func adjustTransitionValue(value float64, spec numericTransitionSpec) float64 {
	if value < spec.min {
		value = spec.min
	} else if value > spec.max {
		value = spec.max
	}
	if spec.integer {
		value = math.Round(value)
	}
	return value
}
